"""Vendor sell prices for crafted items, exported from the game.

TSM's public data has no vendor prices, but the game client does
(GetItemInfo's sellPrice). The CheapestSkillupExport addon records them.

    python -m cheapest_skillup.vendor_sell addon
        Regenerate addon/CheapestSkillupExport/Items.lua from the recipe data
        (run after adding recipes, then copy the addon into the game again).

    python -m cheapest_skillup.vendor_sell import "<WoW>\\WTF\\Account\\<NAME>\\SavedVariables\\CheapestSkillupExport.lua"
        Merge the exported prices into data/vendor_sell.json.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from .recipes import DATA_DIR, available_professions, load_profession

ADDON_DIR = DATA_DIR.parent / "addon" / "CheapestSkillupExport"
SELL_FILE = DATA_DIR / "vendor_sell.json"


def crafted_items() -> dict[int, str]:
    items: dict[int, str] = {}
    for key in available_professions():
        for r in load_profession(key).recipes:
            if r.makes:
                items.setdefault(r.makes, r.name)
    return dict(sorted(items.items()))


def write_addon_items() -> Path:
    lines = ["-- Generated by: python -m cheapest_skillup.vendor_sell addon", "CheapestSkillupExport_Items = {"]
    lines += [f"  {i}, -- {name}" for i, name in crafted_items().items()]
    lines.append("}")
    path = ADDON_DIR / "Items.lua"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _block(text: str, key: str) -> str:
    """Body of `["key"] = { ... }` (flat tables only)."""
    m = re.search(r'\["' + re.escape(key) + r'"\]\s*=\s*\{(.*?)\n\s*\}', text, re.S)
    return m.group(1) if m else ""


def parse_saved_variables(text: str) -> dict[int, tuple[str, int]]:
    """Parse CheapestSkillupExportDB from a WoW SavedVariables file -> {id: (name, sell)}."""
    sells = {int(i): int(v) for i, v in re.findall(r"\[(\d+)\]\s*=\s*(\d+)", _block(text, "sell"))}
    names = {int(i): n.replace('\\"', '"') for i, n in re.findall(r'\[(\d+)\]\s*=\s*"((?:[^"\\]|\\.)*)"', _block(text, "names"))}
    return {i: (names.get(i, ""), s) for i, s in sells.items()}


def import_file(path: Path) -> tuple[int, int]:
    found = parse_saved_variables(path.read_text(encoding="utf-8", errors="replace"))
    data = json.loads(SELL_FILE.read_text(encoding="utf-8")) if SELL_FILE.exists() else {}
    items = data.get("items", {})
    for i, (name, sell) in found.items():
        items[str(i)] = {"name": name or items.get(str(i), {}).get("name", ""), "sell": sell}
    data = {
        "note": "Vendor sell prices (copper) of crafted items, exported in game with the CheapestSkillupExport addon.",
        "items": dict(sorted(items.items(), key=lambda kv: int(kv[0]))),
    }
    SELL_FILE.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    missing = [i for i in crafted_items() if str(i) not in items]
    return len(found), len(missing)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="cheapest_skillup.vendor_sell", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("addon", help="regenerate the addon's item list")
    imp = sub.add_parser("import", help="import the addon's SavedVariables file")
    imp.add_argument("file", type=Path)
    args = ap.parse_args(argv)
    if args.cmd == "addon":
        print(f"Wrote {write_addon_items()} ({len(crafted_items())} items)")
        return 0
    if not args.file.exists():
        print(f"Not found: {args.file}", file=sys.stderr)
        return 2
    n, missing = import_file(args.file)
    print(f"Imported {n} vendor prices into {SELL_FILE}.")
    if missing:
        print(f"{missing} crafted item(s) still have no price; log in, type /csexport, then /reload and import again.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
